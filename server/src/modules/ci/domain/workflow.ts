/**
 * The GitHub Actions workflow emitted to `.github/workflows/devdigest-review.yml`.
 * Pure string builder (domain layer): no Fastify/Drizzle imports, deterministic
 * output. Only two things are configurable (wizard "Configure" step) and both are
 * validated against closed enums, never interpolated as free text: the
 * `pull_request` activity types and how the runner publishes its result.
 *
 * Security by construction (SPEC G5 / AC-9,11,12,13,14 — `security` skill):
 *   - A02 least privilege: `permissions: contents: read, pull-requests: write`.
 *   - A12 fork safety: a job-level `if:` skips PRs whose head is a fork, so no
 *     secret is ever exposed to fork-authored code; `pull_request` (NOT
 *     `pull_request_target`) is used, so untrusted code is never run with
 *     repo secrets in scope.
 *   - A05 injection: author-controlled PR data (title/body/branch/diff) is
 *     NEVER interpolated into a `run:` script. `${{ github.event.* }}` appears
 *     nowhere in `run:`. The runner reads PR number from the `PR_NUMBER` env
 *     and the title/body from the event payload file at `GITHUB_EVENT_PATH` as
 *     DATA, not as shell text.
 *   - A14 no secrets in files: only `secrets.*` / `vars.*` REFERENCES appear;
 *     no secret value is embedded. The runner reads them from the process env.
 *   - A13 pinned actions: the only external action (`actions/checkout`) is
 *     pinned to a full commit SHA; no unpublished action is referenced (AC-9).
 */

/** `actions/checkout@v4.2.2` pinned to its full commit SHA (AC-13). */
const CHECKOUT_SHA = '11bd71901bbe5b1630ceea73d27597364c9af683';

export const WORKFLOW_PATH = '.github/workflows/devdigest-review.yml';
export const RUNNER_ENTRY = '.devdigest/runner/index.js';
export const RUNNER_PACKAGE_JSON = '.devdigest/runner/package.json';
export const MEMORY_PATH = '.devdigest/memory.jsonl';

/**
 * The ncc bundle is an ES module (it ships its own `{"type":"module"}`). The
 * target repo's `.devdigest/runner/` has no package.json, so without this marker
 * Node would have to guess the module type from syntax — which older Node
 * versions on the Actions image do not do.
 */
export const RUNNER_PACKAGE_JSON_CONTENTS = '{\n  "type": "module"\n}\n';

/**
 * Generator version, stamped into the workflow as a comment and stored on the
 * installation so the CI tab can flag an install whose files are out of date.
 * Bump when the generated workflow changes shape.
 *   1 — fixed workflow (v1 export)
 *   2 — configurable triggers + post-as, least-privilege permissions per mode
 */
export const WORKFLOW_VERSION = 2;

export type WorkflowTrigger = 'opened' | 'synchronize' | 'reopened';
export type WorkflowPostAs = 'github_review' | 'pr_comment' | 'none';

export interface WorkflowOptions {
  triggers?: readonly WorkflowTrigger[];
  postAs?: WorkflowPostAs;
}

/** Canonical order so identical selections always produce identical YAML. */
const TRIGGER_ORDER: readonly WorkflowTrigger[] = ['opened', 'synchronize', 'reopened'];
const POST_AS_VALUES: readonly WorkflowPostAs[] = ['github_review', 'pr_comment', 'none'];

export const DEFAULT_TRIGGERS: readonly WorkflowTrigger[] = ['opened', 'synchronize'];

export function generateWorkflowYaml(options: WorkflowOptions = {}): string {
  const requested = options.triggers ?? DEFAULT_TRIGGERS;
  const triggers = TRIGGER_ORDER.filter((t) => requested.includes(t));
  if (triggers.length === 0) throw new Error('Workflow needs at least one pull_request trigger');
  const postAs = options.postAs ?? 'github_review';
  if (!POST_AS_VALUES.includes(postAs)) throw new Error(`Unknown post_as: ${String(postAs)}`);

  // Least privilege (AC-11): the token may write to the PR only when the runner
  // actually publishes a review/comment. Exit-code-only mode just reads the diff.
  const prPermission = postAs === 'none' ? 'read' : 'write';
  const permissionComment =
    postAs === 'none'
      ? 'read code + the PR diff; nothing is posted (exit code only)'
      : 'read code, write PR reviews/comments. Nothing else';

  return `# DevDigest CI review — generated by Export to CI. Review before merging.
# devdigest-workflow-version: ${WORKFLOW_VERSION}
name: DevDigest Review

on:
  pull_request:
    types: [${triggers.join(', ')}]

# Least-privilege token (AC-11): ${permissionComment}.
permissions:
  contents: read
  pull-requests: ${prPermission}

jobs:
  review:
    # Fork safety (AC-12): skip PRs opened from a fork — no secrets are exposed
    # to untrusted code. We use pull_request (not pull_request_target), so the
    # checked-out code never runs with repo secrets for fork PRs.
    if: github.event.pull_request.head.repo.fork == false
    runs-on: ubuntu-latest
    steps:
      - name: Checkout
        uses: actions/checkout@${CHECKOUT_SHA} # v4.2.2
        with:
          fetch-depth: 0

      - name: Run DevDigest review
        # Untrusted PR data (title/body/diff/branch) is NEVER interpolated into
        # this script (AC-13). The runner reads the PR number from PR_NUMBER and
        # the title/body from the event payload file as data, not shell text.
        run: node ${RUNNER_ENTRY}
        env:
          OPENROUTER_API_KEY: \${{ secrets.OPENROUTER_API_KEY }}
          DEVDIGEST_INGEST_TOKEN: \${{ secrets.DEVDIGEST_INGEST_TOKEN }}
          DEVDIGEST_API_URL: \${{ vars.DEVDIGEST_API_URL }}
          DEVDIGEST_POST_AS: ${postAs}
          GITHUB_TOKEN: \${{ secrets.GITHUB_TOKEN }}
          PR_NUMBER: \${{ github.event.pull_request.number }}
`;
}

/**
 * Guard for a member-edited workflow (wizard Preview). Not a full linter — it
 * rejects the one construct that would break the security model (AC-12): a
 * `pull_request_target` trigger, which runs with secrets in scope. The edited
 * file still ships through a PR the member reviews.
 */
export function assertWorkflowSafe(yaml: string): void {
  const offending = yaml
    .split('\n')
    .filter((l) => !l.trim().startsWith('#'))
    .some((l) => l.includes('pull_request_target'));
  if (offending) {
    throw new Error('The workflow must not use pull_request_target (secrets would reach untrusted code).');
  }
}
