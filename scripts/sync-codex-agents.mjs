#!/usr/bin/env node
/**
 * Portability sync: Claude Code -> OpenAI Codex.
 *
 * SOURCE OF TRUTH stays in `.claude/` (agents: `.claude/agents/*.md`, skills:
 * `.claude/skills/*`). This script derives the Codex-native equivalents so the
 * same roster works in both tools without hand-maintained copies:
 *
 *   .claude/agents/<name>.md      ->  .codex/agents/<name_snake>.toml   (generated)
 *   .claude/skills/<skill>/       ->  .agents/skills/<skill>            (relative symlink)
 *
 * Usage:
 *   node scripts/sync-codex-agents.mjs           # (re)generate
 *   node scripts/sync-codex-agents.mjs --check   # exit 1 if anything is out of date (CI/pre-commit)
 *
 * No dependencies. Never edit `.codex/agents/*.toml` by hand — edit the `.md` and re-run.
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync, lstatSync, readlinkSync, symlinkSync, rmSync, statSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const AGENTS_SRC = join(ROOT, '.claude/agents');
const SKILLS_SRC = join(ROOT, '.claude/skills');
const AGENTS_OUT = join(ROOT, '.codex/agents');
const SKILLS_OUT = join(ROOT, '.agents/skills');
const CHECK = process.argv.includes('--check');

const problems = [];
const note = (msg) => problems.push(msg);

/** Minimal frontmatter parser: `key: value` lines plus one `skills:` block list. */
function parseAgent(file) {
  const raw = readFileSync(file, 'utf8');
  const m = raw.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  if (!m) throw new Error(`${file}: missing frontmatter`);
  const fm = { skills: [] };
  let inSkills = false;
  for (const line of m[1].split('\n')) {
    const item = line.match(/^\s+-\s+([\w-]+)/);
    if (inSkills && item) {
      fm.skills.push(item[1]);
      continue;
    }
    const kv = line.match(/^([\w-]+):\s*(.*)$/);
    if (!kv) continue;
    inSkills = kv[1] === 'skills';
    if (!inSkills) fm[kv[1]] = kv[2].trim();
  }
  return { fm, body: m[2].trim() };
}

const tomlStr = (s) => `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
const tomlBlock = (s) => `"""\n${s.replace(/\\/g, '\\\\').replace(/"""/g, '\\"\\"\\"')}\n"""`;

function runtimeNotes({ fm, readOnly }) {
  const lines = [
    '## Codex runtime notes (generated — the rules below were written for Claude Code)',
    '',
    '- Tool names in the rules below (`Read`, `Grep`, `Glob`, `Write`, `Edit`, `WebSearch`, `WebFetch`) are Claude Code names. In Codex use the shell (`rg`, `cat`, `sed -n`, `ls`, `git`), `apply_patch` for edits, and web search when it is enabled.',
    readOnly
      ? '- This agent runs with `sandbox_mode = "read-only"`, which Codex ENFORCES: any attempt to create, edit or delete files (including via the shell) will fail — do not try to work around it.'
      : '- This agent runs with `sandbox_mode = "workspace-write"`. Codex cannot restrict writes to particular paths, so the path limits in "Hard constraints" below are conventions you must follow yourself (check `git status --porcelain` before finishing).',
    '- Do not spawn further subagents.',
    '- Project rules live in `AGENTS.md` (root and per-module); read them as the rules below instruct.',
  ];
  if (fm.skills.length > 0) {
    lines.push(
      '- Skills: Claude Code preloads these skills; here, open the `SKILL.md` of each one that applies to the files you touch BEFORE acting (they are discoverable under `.agents/skills/`): ' +
        fm.skills.map((s) => `\`.agents/skills/${s}/SKILL.md\``).join(', ') +
        '.',
    );
  }
  return lines.join('\n');
}

function buildToml(file) {
  const { fm, body } = parseAgent(file);
  const tools = (fm.tools ?? '').split(',').map((t) => t.trim());
  const readOnly = !tools.includes('Write') && !tools.includes('Edit');
  const codexName = fm.name.replace(/-/g, '_');
  const toml = [
    `# GENERATED by scripts/sync-codex-agents.mjs from .claude/agents/${fm.name}.md — DO NOT EDIT.`,
    `# Edit the .md source and re-run: node scripts/sync-codex-agents.mjs`,
    `name = ${tomlStr(codexName)}`,
    `description = ${tomlStr(fm.description)}`,
    `sandbox_mode = ${tomlStr(readOnly ? 'read-only' : 'workspace-write')}`,
    // \`model\` is intentionally omitted: the Claude alias (\`sonnet\`) is meaningless in Codex,
    // so the agent inherits the model of the Codex session.
    `developer_instructions = ${tomlBlock(`${runtimeNotes({ fm, readOnly })}\n\n${body}`)}`,
    '',
  ].join('\n');
  return { out: join(AGENTS_OUT, `${codexName}.toml`), toml, codexName };
}

function syncFile(path, content) {
  const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
  if (current === content) return;
  if (CHECK) return note(`out of date: ${path.replace(ROOT + '/', '')}`);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
  console.log(`wrote ${path.replace(ROOT + '/', '')}`);
}

// ---- agents -----------------------------------------------------------------
const wanted = new Set();
for (const f of readdirSync(AGENTS_SRC).filter((f) => f.endsWith('.md') && f !== 'README.md').sort()) {
  const { out, toml } = buildToml(join(AGENTS_SRC, f));
  wanted.add(out);
  syncFile(out, toml);
}
if (existsSync(AGENTS_OUT)) {
  for (const f of readdirSync(AGENTS_OUT).filter((f) => f.endsWith('.toml'))) {
    const p = join(AGENTS_OUT, f);
    if (wanted.has(p)) continue;
    if (CHECK) note(`stale (no .claude/agents source): .codex/agents/${f}`);
    else {
      rmSync(p);
      console.log(`removed stale .codex/agents/${f}`);
    }
  }
}

// ---- skills (relative symlinks; Codex follows symlinked skill folders) ------------
const skillDirs = readdirSync(SKILLS_SRC).filter((d) => existsSync(join(SKILLS_SRC, d, 'SKILL.md'))).sort();
for (const d of skillDirs) {
  const link = join(SKILLS_OUT, d);
  const target = join('..', '..', '.claude', 'skills', d);
  let ok = false;
  try {
    ok = lstatSync(link).isSymbolicLink() && readlinkSync(link) === target;
  } catch {}
  if (ok) continue;
  if (CHECK) {
    note(`missing/incorrect skill link: .agents/skills/${d}`);
    continue;
  }
  mkdirSync(SKILLS_OUT, { recursive: true });
  if (existsSync(link) || (() => { try { lstatSync(link); return true; } catch { return false; } })()) rmSync(link, { recursive: true, force: true });
  symlinkSync(target, link, 'dir');
  console.log(`linked .agents/skills/${d} -> ${target}`);
}

if (CHECK) {
  if (problems.length) {
    console.error(problems.join('\n') + '\n\nRun: node scripts/sync-codex-agents.mjs');
    process.exit(1);
  }
  console.log('codex agents + skills are in sync');
} else {
  console.log(`done: ${wanted.size} agent(s), ${skillDirs.length} skill link(s)`);
}
